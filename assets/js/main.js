const CV = { pt: "cv/CV_Bruno_Nogueira_PT.pdf", en: "cv/CV_Bruno_Nogueira_EN.pdf" };
const META = {
  pt: { title: document.title, lang: "pt-BR" },
  en: { title: "Bruno Glória Nogueira · Operations and Commercial Leadership", lang: "en" }
};

const nodes = document.querySelectorAll("[data-i18n]");
nodes.forEach(el => { el.dataset.pt = el.innerHTML; });

function setLang(lang) {
  nodes.forEach(el => {
    const key = el.dataset.i18n;
    el.innerHTML = lang === "en" && EN[key] ? EN[key] : el.dataset.pt;
  });
  document.documentElement.lang = META[lang].lang;
  document.title = META[lang].title;
  document.querySelectorAll(".js-cv").forEach(a => { a.href = CV[lang]; });
  document.querySelectorAll("[data-lang]").forEach(b => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
  });
  const out = document.querySelector(".email-out");
  if (out && out.textContent) revealEmail();
  try { localStorage.setItem("lang", lang); } catch (e) {}
}

document.querySelectorAll("[data-lang]").forEach(b => {
  b.addEventListener("click", () => setLang(b.dataset.lang));
});

let saved = null;
try { saved = localStorage.getItem("lang"); } catch (e) {}
const initial = saved || (navigator.language && !navigator.language.toLowerCase().startsWith("pt") ? "en" : "pt");
if (initial === "en") setLang("en");

// E-mail montado só no clique, para reduzir spam de robôs que leem a página.
function revealEmail() {
  const btn = document.querySelector(".js-email");
  const out = document.querySelector(".email-out");
  const addr = btn.dataset.user + "@" + btn.dataset.domain;
  out.innerHTML = '<a href="mailto:' + addr + '">' + addr + "</a>";
}
document.querySelector(".js-email").addEventListener("click", revealEmail);

// Menu no celular
const toggle = document.querySelector(".nav-toggle");
const links = document.getElementById("nav-links");
toggle.addEventListener("click", () => {
  const open = links.classList.toggle("open");
  toggle.setAttribute("aria-expanded", String(open));
});
links.querySelectorAll("a").forEach(a => a.addEventListener("click", () => {
  links.classList.remove("open");
  toggle.setAttribute("aria-expanded", "false");
}));

// Animação suave ao rolar
if ("IntersectionObserver" in window) {
  const targets = document.querySelectorAll(".metric, .case, .timeline li, .principles li");
  targets.forEach(t => t.classList.add("reveal"));
  const io = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting) { e.target.classList.add("is-visible"); io.unobserve(e.target); }
    });
  }, { threshold: 0.12 });
  targets.forEach(t => io.observe(t));
}
